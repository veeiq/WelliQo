import fs from 'fs';
import path from 'path';

// Define the grouping of categories to topics
const topicMap = {
  'protein': ['Protein Optimization', 'Plant-Based Basics', 'Vegetarian Living', 'Vegan Living', 'Eggitarian'],
  'hydration': ['Hydration & Electrolytes'],
  'diet': ['Weight Management', 'Caloric Density', 'Dining Out & Social Eating', 'Budget-Friendly Nutrition'],
  'heart': ['Heart Health', 'Sodium & Heart Health', 'Healthy Fats & Omega-3s'],
  'gut': ['Fiber & Gut Transit', 'Gut Health & Digestion', 'Lactose Intolerance', 'Gluten-Free Eating', 'Nut Allergies', 'Food Allergies & Intolerances'],
  'metabolic': ['Metabolic Health & Blood Sugar', 'Sugar & Sweeteners', 'Complex Carbs & Glycemic Index'],
  'cooking': ['Healthy Cooking Fundamentals'],
  'mental': ['Stress & Mental Wellbeing', 'Sleep Optimization', 'Mindful Eating'],
  'lifestyle': ["Women's Health", "Men's Health", 'Senior Nutrition'],
  'general': ['Micronutrients (Vitamins/Minerals)', 'Religious Food Preferences', 'Supplements & Ergogenic Aids']
};

const ARTICLES_PATH = './apps/web/src/data/knowledge/articles.ts';
const OUTPUT_PATH = './apps/web/src/data/knowledge/image-mapping.ts';

function main() {
  const content = fs.readFileSync(ARTICLES_PATH, 'utf-8');
  
  // Extract all articles with their IDs and categories
  const articleRegex = /id:\s*['\"](ART\d+)['\"].*?category:\s*['\"]([^'\"]+)['\"]/gs;
  let match;
  const articles = [];
  
  while ((match = articleRegex.exec(content)) !== null) {
    articles.push({
      id: match[1],
      category: match[2]
    });
  }

  console.log(`Found ${articles.length} articles.`);

  // Map each category to a topic
  const categoryToTopic = {};
  for (const [topic, categories] of Object.entries(topicMap)) {
    for (const cat of categories) {
      categoryToTopic[cat] = topic;
    }
  }

  // Assign images to articles sequentially per topic
  // e.g., protein_01.webp, protein_02.webp, up to 10
  const IMAGES_PER_TOPIC = 10;
  const topicCounts = {};
  const mapping = {};

  for (const article of articles) {
    const topic = categoryToTopic[article.category] || 'general';
    if (!topicCounts[topic]) {
      topicCounts[topic] = 1;
    }
    
    // Cycle through 1 to IMAGES_PER_TOPIC
    const index = ((topicCounts[topic] - 1) % IMAGES_PER_TOPIC) + 1;
    const formattedIndex = index.toString().padStart(2, '0');
    
    mapping[article.id] = `/images/articles/${topic}_${formattedIndex}.webp`;
    
    topicCounts[topic]++;
  }

  console.log('Image distribution:', topicCounts);

  // Generate the image-mapping.ts file
  let mappingFileContent = `// Automatically generated by scripts/generate-image-mapping.mjs
// Maps article IDs to their local image paths

export const imageMapping: Record<string, string> = {\n`;

  for (const [id, imagePath] of Object.entries(mapping)) {
    mappingFileContent += `  '${id}': '${imagePath}',\n`;
  }

  mappingFileContent += `};\n\n`;
  
  mappingFileContent += `export function getArticleImage(articleId: string): string {
  return imageMapping[articleId] || '/images/articles/general_01.webp';
}
`;

  fs.writeFileSync(OUTPUT_PATH, mappingFileContent);
  console.log(`Wrote mapping to ${OUTPUT_PATH}`);
}

main();
